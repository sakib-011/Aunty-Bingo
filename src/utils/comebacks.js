export function getComebacksForTile(tile, lang = 'bn') {
  if (!tile) return GENERIC_COMEBACKS[lang]?.[0] || GENERIC_COMEBACKS.bn[0];

  // If the tile has direct AI-generated comebacks attached, prioritize them for 100% exact match!
  if (tile.comebacks) {
    if (tile.comebacks[lang]) {
      return tile.comebacks[lang];
    }
    if (tile.comebacks.savage && typeof tile.comebacks.savage === 'object') {
      return {
        polite: tile.comebacks.polite?.[lang] || tile.comebacks.polite?.bn || '',
        savage: tile.comebacks.savage?.[lang] || tile.comebacks.savage?.bn || '',
        funny: tile.comebacks.funny?.[lang] || tile.comebacks.funny?.bn || ''
      };
    }
    return tile.comebacks;
  }

  const bnText = (tile.bn || '').toLowerCase();
  const enText = (tile.en || '').toLowerCase();
  const combined = `${bnText} ${enText}`;

  for (const item of CURATED_COMEBACKS) {
    const matched = item.keywords.some((k) => combined.includes(k.toLowerCase()));
    if (matched) {
      return item[lang] || item.bn;
    }
  }

  const list = GENERIC_COMEBACKS[lang] || GENERIC_COMEBACKS.bn;
  const index = Math.abs(Number(tile.id) || 0) % list.length;
  return list[index] || list[0];
}